#!/usr/bin/env bash
set -e

# Directories
REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SERVICES_DIR="$REPO_ROOT/services"

# Function to setup dummy secrets for a service
setup_dummy_secrets() {
  local service_path="$1"
  if [ -d "$service_path/secrets" ]; then
    echo "⚙️  Setting up dummy secrets in $service_path/secrets..."
    # Find all files in the secrets directory that aren't empty and don't end in .sops.yaml
    # Actually, we'll just check if there's a compose.yml and parse it or simply 
    # touch files if they are declared. To be simple, we look at the 'secrets:' block
    # in compose.yml if possible, or just touch any file that isn't a directory.
    # A simple grep can find secrets file paths.
    if grep -q "file: ./secrets/" "$service_path/compose.yml"; then
      grep -Eo "file: \./secrets/[a-zA-Z0-9_-]+" "$service_path/compose.yml" | awk -F'/' '{print $NF}' | while read -r secret_file; do
        if [ ! -f "$service_path/secrets/$secret_file" ]; then
          echo "dummy_secret_value" > "$service_path/secrets/$secret_file"
          echo "   Created dummy secret: $secret_file"
        fi
      done
    fi
  fi
}

start_service() {
  local service_name="$1"
  local service_path="$SERVICES_DIR/$service_name"
  
  if [ ! -d "$service_path" ]; then
    echo "❌ Service '$service_name' not found in $SERVICES_DIR"
    exit 1
  fi
  
  echo "🚀 Starting $service_name..."
  setup_dummy_secrets "$service_path"
  
  # Ensure necessary local volumes directories exist so docker doesn't create them as root
  # We grep for ${HOME}/volumes or ~/volumes
  if grep -q "\${HOME}/volumes/" "$service_path/compose.yml"; then
    grep -Eo "\$\{HOME\}/volumes/[a-zA-Z0-9_/-]+" "$service_path/compose.yml" | while read -r vol_path; do
      # Expand ${HOME}
      local eval_path
      eval_path=$(eval echo "$vol_path")
      mkdir -p "$eval_path"
    done
  fi

  # Identify container CLI and start
  if command -v podman-compose >/dev/null 2>&1; then
    CONTAINER_CLI="podman"
    
    # CRITICAL FIX FOR MAC PODMAN VM (SELinux):
    # The Fedora CoreOS VM inside Podman Machine enforces SELinux labels.
    # Containers that mount the Podman socket (like socket-proxy) get blocked
    # by SELinux even with correct Unix permissions. We generate a temporary
    # compose override that adds `label=disable` to bypass this for LOCAL
    # testing only. This override file is gitignored and auto-cleaned.
    export DOCKER_SOCK="/run/user/501/podman/podman.sock"
    
    local override_file="$service_path/compose.override.yml"
    # Auto-generate override for services that mount the docker socket
    if grep -q "docker.sock" "$service_path/compose.yml" 2>/dev/null; then
      local svc_name
      svc_name=$(grep -A1 "docker.sock" "$service_path/compose.yml" | head -1)
      # Extract the service key that owns the docker.sock volume
      svc_name=$(awk '/services:/,0' "$service_path/compose.yml" | grep -E '^\s{2}[a-z]' | head -1 | tr -d ' :')
      cat > "$override_file" <<EOF
# AUTO-GENERATED by test-compose.sh — DO NOT COMMIT
services:
  ${svc_name}:
    security_opt:
      - no-new-privileges=true
      - label=disable
EOF
      echo "   🔧 Generated SELinux override for $service_name ($override_file)"
    fi
    
    (cd "$service_path" && podman-compose up -d)
    
    # Clean up override after compose reads it
    rm -f "$override_file" 2>/dev/null
  elif command -v docker >/dev/null 2>&1; then
    CONTAINER_CLI="docker"
    (cd "$service_path" && docker compose up -d)
  else
    echo "❌ Neither podman-compose nor docker found in PATH."
    exit 1
  fi
}

# --- Main Logic ---

echo "🐳 Local Compose Testing Script"

# Determine docker or podman for network creation
CONTAINER_CLI="docker"
if command -v podman >/dev/null 2>&1; then
  CONTAINER_CLI="podman"
fi

# Parse flags
FORCE_AMD64=false
if [[ "$1" == "--amd64" ]]; then
  FORCE_AMD64=true
  export DOCKER_DEFAULT_PLATFORM=linux/amd64
  shift
fi

# 1. Create necessary external networks if they don't exist
$CONTAINER_CLI network inspect edge-network >/dev/null 2>&1 || $CONTAINER_CLI network create edge-network
$CONTAINER_CLI network inspect socket-proxy >/dev/null 2>&1 || $CONTAINER_CLI network create socket-proxy

# 2. Check if user provided a service to start
if [ $# -eq 0 ]; then
  echo "Usage: $0 [--amd64] <service-name> [additional-services...]"
  echo "Example: $0 calibre-web"
  echo "Hint: If you want to test the full proxy stack, run: $0 socket-proxy traefik-public calibre-web"
  echo "Hint: Use --amd64 as the first argument to force x86_64 emulation on Apple Silicon."
  exit 0
fi

# 3. Iterate and start requested services
for srv in "$@"; do
  start_service "$srv"
done

echo "✅ All requested services started."

# Launch Kitty tabs for logs if running inside Kitty
if [ "$TERM" = "xterm-kitty" ]; then
  if command -v kitty >/dev/null 2>&1; then
    echo "🐱 Opening Kitty tabs for logs..."
    for srv in "$@"; do
      if command -v podman-compose >/dev/null 2>&1; then
        LOG_CMD="export DOCKER_SOCK=/run/user/501/podman/podman.sock && podman-compose logs -f"
      else
        LOG_CMD="docker compose logs -f"
      fi
      kitty @ launch --type=tab --tab-title="Logs: $srv" --keep-focus zsh -lc "cd $SERVICES_DIR/$srv && $LOG_CMD; echo ''; echo 'Press Enter to close...'; read" 2>/dev/null || echo "   ⚠️ Could not open Kitty tab for $srv. (Check if 'allow_remote_control yes' is in kitty.conf)"
    done
  fi
else
  echo "🔍 Use '$CONTAINER_CLI ps' to verify or '$CONTAINER_CLI compose -f services/<service>/compose.yml logs -f' to view logs."
fi
